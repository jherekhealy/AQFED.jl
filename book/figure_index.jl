# Cross-reference between the book figures and the code that generates them.
# For every \includegraphics of the book chapters, finds the figure \label and the Julia files and lines
# that write a PDF of the same name (including commented-out plotting code), and writes book/FIGURES.md.
# Usage: julia book/figure_index.jl [path/to/eqd_book]

const BOOK_DIR = length(ARGS) >= 1 ? ARGS[1] : expanduser("~/mypapers/eqd_book")
const CODE_DIRS = [joinpath(@__DIR__, "..", "test"), @__DIR__]

struct BookFigure
    pdf::String
    label::String
    texFile::String
    line::Int
end

struct CodeRef
    file::String
    line::Int
    isComment::Bool
end

pdfName(s) = endswith(s, ".pdf") ? basename(s) : basename(s) * ".pdf"

#expands "a_{vol,dens}.pdf" into ["a_vol.pdf", "a_dens.pdf"]
function expandBraces(s::AbstractString)
    m = match(r"\{([^{}]*)\}", s)
    m === nothing && return [String(s)]
    head, tail = s[1:m.offset-1], s[m.offset+length(m.match):end]
    return reduce(vcat, [expandBraces(head * part * tail) for part in split(m.captures[1], ",")])
end

function bookFigures(bookDir)
    figures = BookFigure[]
    for (root, _, files) in walkdir(bookDir), f in files
        (endswith(f, ".tex") && occursin(r"^chapter-|^appendix-", basename(root))) || continue
        path = joinpath(root, f)
        lines = readlines(path)
        inFigure, current, label = false, Tuple{String,Int}[], ""
        for (i, l) in enumerate(lines)
            code = replace(l, r"(?<!\\)%.*" => "")
            if occursin("\\begin{figure", code)
                inFigure, current, label = true, Tuple{String,Int}[], ""
            end
            for m in eachmatch(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", code)
                push!(current, (pdfName(m.captures[1]), i))
            end
            for m in eachmatch(r"\\label\{(fig:[^}]+)\}", code)
                label = m.captures[1] #the last label is the one of the whole figure
            end
            if occursin("\\end{figure", code) || (!inFigure && !isempty(current))
                append!(figures, [BookFigure(pdf, label, relpath(path, bookDir), line) for (pdf, line) in current])
                inFigure, current, label = false, Tuple{String,Int}[], ""
            end
        end
    end
    return figures
end

function codeRefs(dirs)
    refs = Dict{String,Vector{CodeRef}}()
    for dir in dirs, (root, _, files) in walkdir(dir), f in files
        endswith(f, ".jl") || continue
        path = joinpath(root, f)
        depth = 0 #block comment nesting
        for (i, l) in enumerate(readlines(path))
            depthBefore = depth
            for m in eachmatch(r"#=|=#", l)
                depth += m.match == "#=" ? 1 : -1
            end
            for m in eachmatch(r"[\w\-./{},~]+\.pdf", l), pdf in expandBraces(m.match)
                isComment = depthBefore > 0 || depth > 0 || occursin(r"^\s*#", l)
                push!(get!(refs, basename(pdf), CodeRef[]), CodeRef(relpath(path, joinpath(@__DIR__, "..")), i, isComment))
            end
        end
    end
    return refs
end

function writeIndex(io, figures, refs)
    println(io, "# Book figures and generating code\n")
    println(io, "Generated by `julia book/figure_index.jl`. A figure without code reference is listed under *Missing*.\n")
    println(io, "| Label | PDF | Book | Code |")
    println(io, "|---|---|---|---|")
    missingFigures = BookFigure[]
    for fig in sort(figures, by=f -> (f.texFile, f.line))
        r = get(refs, fig.pdf, CodeRef[])
        isempty(r) && push!(missingFigures, fig)
        code = join(["[$(c.file):$(c.line)](../$(c.file)#L$(c.line))" * (c.isComment ? " (commented)" : "") for c in r], "<br>")
        println(io, "| `$(fig.label)` | $(fig.pdf) | $(fig.texFile):$(fig.line) | $(isempty(r) ? "**missing**" : code) |")
    end
    println(io, "\n## Missing ($(length(missingFigures)) of $(length(figures)))\n")
    for fig in missingFigures
        println(io, "- `$(fig.label)` $(fig.pdf) ($(fig.texFile):$(fig.line))")
    end
    return missingFigures
end

function main()
    figures = bookFigures(BOOK_DIR)
    refs = codeRefs(CODE_DIRS)
    out = joinpath(@__DIR__, "FIGURES.md")
    missingFigures = open(io -> writeIndex(io, figures, refs), out, "w")
    println("$(length(figures)) figures, $(length(figures) - length(missingFigures)) with code, $(length(missingFigures)) missing -> $out")
end

main()
